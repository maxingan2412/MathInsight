"""教师主观评价 → 结构化标签。

离线版用关键词规则，保证无网络也能跑；配置了大模型接口时，可改用 llm.tag_comment()
得到更细的标签。标签分「学习习惯」「思维特点」「心态」三类，正负两向。
"""
from __future__ import annotations

import re

RULES = [
    ("学习习惯", "-", "计算粗心", r"粗心|马虎|算错|计算.*(失误|不稳|出错)"),
    ("学习习惯", "-", "审题不细", r"审题|看错|漏看|读题"),
    ("学习习惯", "-", "书写不规范", r"书写|步骤不全|跳步|表述|规范"),
    ("学习习惯", "-", "作业拖延", r"拖延|不按时|迟交|应付"),
    ("学习习惯", "+", "订正及时", r"订正|错题本|整理错题|及时复盘"),
    ("学习习惯", "+", "基础扎实", r"基础(扎实|好|牢)|概念清楚"),
    ("思维特点", "+", "思维活跃", r"思维活跃|反应快|有想法|爱提问|善于思考"),
    ("思维特点", "+", "善于数形结合", r"数形结合|画图|几何直观"),
    ("思维特点", "-", "综合题畏难", r"畏难|压轴.*(放弃|空)|不敢下手|综合题.*(弱|差)"),
    ("思维特点", "-", "方法单一", r"套路|死记|方法单一|不会变通|题型化"),
    ("思维特点", "-", "逻辑表达弱", r"逻辑|推理.*(弱|不严)|证明.*(弱|乱)"),
    ("心态", "-", "考试紧张", r"紧张|心态|焦虑|发挥失常"),
    ("心态", "-", "时间分配不当", r"时间(不够|分配)|做不完|前面.*慢"),
    ("心态", "+", "学习主动", r"主动|自觉|认真|积极"),
]
_RX = [(cat, sign, tag, re.compile(p)) for cat, sign, tag, p in RULES]


def tag_comment(text: str) -> list[dict]:
    out = []
    for cat, sign, tag, rx in _RX:
        if rx.search(text or ""):
            out.append({"category": cat, "sign": sign, "tag": tag})
    return out
